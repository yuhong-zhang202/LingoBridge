/**
 * @module   quota-period
 * @desc     额度「日界 / 月界」的唯一口径出口 —— 全部按**东八区**（UTC+8）分桶。
 *
 *   【为什么存在这个模块】改动前全站有三套并存的日期口径，用户被夹在中间：
 *     · 日额度：Postgres `current_date` 跟随库/容器时区（生产实为 UTC）→ 香港时间早上 8 点才重置，
 *       而全站文案写的是「明天会自动恢复」。凌晨 0 点半打开产品的人仍被拦，且无从理解为什么。
 *     · 月额度：客户端 `new Date().getMonth()` 跟随**设备**时区、服务端跟随**容器**时区。
 *       每月 1 日 00:00–08:00 这 8 小时两端不同月，会出现「本月额度已用完」配「0 / 10」进度条
 *       ——一个自相矛盾的界面，配一个点了必然再被 402 拦的按钮。
 *     · 看板与打卡：早已显式东八区（dashboard-shared 的 HK_OFFSET_MS、迁移 0026 的
 *       `(now() at time zone 'Asia/Shanghai')::date`）。
 *   本模块把额度这一路并入既有的东八区口径，**不引入第四套写法**：
 *   TS 侧沿用看板的固定偏移量（lib/date 的 HK_OFFSET_MS），SQL 侧沿用 0026 的 `at time zone 'Asia/Shanghai'`。
 *   两者语义等价（东八区自 1991 年起无夏令时，全年恒定 +8）。
 *
 *   【一处收敛】凡「按天/按月分桶的额度计数」一律从这里取下界，客户端与服务端共用同一份实现
 *   （本文件无 'server-only'、无 DOM 依赖，两侧都能 import）。客户端预检与服务端硬闸从此
 *   逐字同口径，上面那个「自相矛盾的界面」在结构上不再可能出现。
 *
 *   【可测性】所有函数都接受可注入的 `now`，日界逻辑不依赖跑测试时的真实时钟。
 *
 * @author   LingoBridge
 * @created  2026-08-12
 */
import { hkDayKey, hkMonthStartMs } from './date'

/**
 * 一次性切换守卫的失效时刻 = 东八区 2026-09-01 00:00（UTC 2026-08-31 16:00）。
 * 语义见 quotaMonthStartISO 的「只多不少」论证。到期后本常量与它的分支即为死代码，
 * ⚠️ 2026-09-01 之后可连同 quota-period.test.ts 里对应的两个用例一起删除，删掉不改变任何行为。
 */
export const MONTH_TZ_SWITCH_GRACE_UNTIL_MS = Date.UTC(2026, 8, 1) - 8 * 60 * 60 * 1000

/**
 * 额度日桶键（`YYYY-MM-DD`，东八区）。用于读 `daily_usage_counts.day` ——
 * 该列自迁移 0062 起由 RPC 按东八区写入，读写必须同口径，否则香港 00:00–08:00 会读错桶。
 *
 * 【切换方向：只多不少，不存在「少给」路径】日额度是**按桶键查表**（day 是主键的一部分），
 * 不是按时间范围扫行，所以只需看「新桶键此刻已有多少行」。设切换时刻为 T：
 *   · T 落在香港 08:00–24:00 → 东八区日期与 UTC 日期相同 → 桶键不变，计数原样延续（不多不少）；
 *   · T 落在香港 00:00–08:00 → 东八区日期比 UTC 日期大 1 → 落到一个**必然为空**的新桶。
 *     为什么必然为空：旧口径写进 `day = D` 的行，只可能产生于 UTC 的 D 日，
 *     即香港 D 日 08:00 至 D+1 日 08:00 —— 那段时间整体晚于 T，此刻还不存在。
 *   形式化：`已用_新(T) = #{s ≤ T : UTC日期(s) = 东八区日期(T)}`，而东八区日期(T) ∈ {UTC日期(T), UTC日期(T)+1}，
 *   取 +1 时该集合恒空。故两种情形下当日可用次数都 ≥ 旧口径，切换当天绝不会有人「正用着突然被拦」。
 *   （⚠️ 别拿「时间窗口谁更早」来推：东八区日窗的起点确实比 UTC 日窗早 8 小时，但那 8 小时的增量
 *     早已被写进【前一天】的桶里，不在本桶内。按窗口推会得出相反且错误的结论 —— 月额度才是按窗口算的，
 *     两者的连续性必须分开论证，见下。）
 *
 * 【终身累计不受影响】readLifetimeUsageServer 对同 user+kind 的所有 day 行求和，
 * 桶怎么分不改变增量总数，匿名转写的终身闸不会因本次切换被放开。
 *
 * @param  now  真实时刻，默认当前
 * @returns     东八区日期键，如 `2026-08-03`
 */
export function quotaDayKey(now: Date = new Date()): string {
  return hkDayKey(now)
}

/**
 * 额度月桶下界的 ISO 字符串（`created_at >= 本值` 即计入本月用量）。
 *
 * 【常态口径】东八区当月 1 日 00:00 —— 与用户理解的「这个月」一致，也与 nextMonthFirstLabel
 * 显示的重置日一致。
 *
 * 【一次性切换守卫：为什么不可能出现「少给」】月额度与日额度的结构不同：它是
 * `count(*) where created_at >= 下界` 的**范围查询**，下界往前挪就会把旧行追算进来。
 * 于是单纯改成东八区**会有**一条少给路径：
 * 东八区月初比 UTC 月初早 8 小时，于是「东八区 1 日 00:00–08:00 创建的语料」在旧服务端口径里
 * 算上个月、新口径里算这个月 —— 对本月已快用满的人，等于当场少给几次。这是产品方明确不接受的方向。
 * 故在切换当月取 `max(东八区月初, UTC 月初)` 作下界：
 *   · 东八区 1 日 00:00–08:00（旧 UTC 口径还停在上个月）→ max 取东八区月初 = 新月新额度，
 *     这正是本次要修的那一下，方向是「多给」；
 *   · 其余时间 → max 取 UTC 月初 = 与旧服务端逐字相同，那 8 小时的语料不被追算进本月。
 * 在守卫有效期内（= 切换当月，也正是「新旧口径需要对比」的唯一时段），对**任意**设备时区都成立：
 * 旧的实际生效下界是 min(设备月初, UTC 月初)（客户端先拦、服务端 402 兜底，严的一方说了算），
 * 而 max(东八区月初, UTC 月初) ≥ UTC 月初 ≥ min(设备月初, UTC 月初) ——
 * 新下界永不早于旧下界 ⇒ 计入本月的行只会更少 ⇒ 剩余额度只会更多。
 *
 * 【为什么守卫能安全到期】到期时刻正是东八区 9 月 1 日 00:00 —— 那一刻所有人的月计数本就归零重来
 * （下界 = 此刻本身，本月已用必为 0），切回纯东八区口径不可能让任何人的剩余额度变少。
 * 到期后代价也归零：8 月 1 日 00:00–08:00 的语料在 8 月余下时间既不算 7 月也不算 8 月
 * （一次性、封闭的一小批行，方向仍是「多给」）。9 月起每月一律是完整对齐的东八区自然月，
 * 不存在「旧口径」可比 —— 那时的月初 8 小时本来就该算新月。
 *
 * @param  now  真实时刻，默认当前
 * @returns     月桶下界的 ISO 时间戳字符串
 */
export function quotaMonthStartISO(now: Date = new Date()): string {
  const hkStartMs = hkMonthStartMs(now)
  if (now.getTime() >= MONTH_TZ_SWITCH_GRACE_UNTIL_MS) return new Date(hkStartMs).toISOString()
  const utcStartMs = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), 1)
  return new Date(Math.max(hkStartMs, utcStartMs)).toISOString()
}
